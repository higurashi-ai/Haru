// UI strings of the app in the nine languages of the model. The UI language is
// the card's language, chosen on the setup screen. The keys shared with the web
// client keep its wording (client/src/i18n).

import Foundation

enum UILanguage {
    static let supported = ["en", "ja", "zh", "ko", "es", "fr", "de", "pt", "ru"]
    private static let key = "uiLanguage"
    /// The language chosen last time, English the first time.
    static var current: String = {
        let stored = UserDefaults.standard.string(forKey: key) ?? "en"
        return supported.contains(stored) ? stored : "en"
    }() {
        didSet { UserDefaults.standard.set(current, forKey: key) }
    }
}

/// The string of `key` in the current UI language, with `{name}` replaced by `params[name]`.
func t(_ key: String, _ params: [String: Any] = [:]) -> String {
    var text = uiStrings[UILanguage.current]?[key] ?? uiStrings["en"]?[key] ?? key
    for (name, value) in params { text = text.replacingOccurrences(of: "{\(name)}", with: "\(value)") }
    return text
}

/// Whether `key` has a string (preset labels are looked up by their id).
func hasString(_ key: String) -> Bool { uiStrings["en"]?[key] != nil }

